const resolveTheme = (mode) =>
  mode === 'auto' ? (themeMedia.matches ? 'light' : 'dark') : mode

const applyTheme = (mode, persist = true) => {
  themeMode = ['auto', 'light', 'dark'].includes(mode) ? mode : 'dark'
  const resolved = resolveTheme(themeMode)

  root.dataset.theme = resolved
  root.dataset.themeMode = themeMode

  document.querySelectorAll('[data-theme-set]').forEach((btn) => {
    const active = btn.dataset.themeSet === themeMode
    btn.setAttribute('aria-pressed', String(active))
    btn.setAttribute('aria-checked', String(active))
  })

  updateThemeLabel()

  const meta = document.querySelector('meta[name="theme-color"]')
  if (meta) meta.setAttribute('content', resolved === 'light' ? '#fdfaf6' : '#08070a')

  if (persist) store(THEME_KEY, themeMode)
}

