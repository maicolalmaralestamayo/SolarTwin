const root = document.documentElement
const THEME_KEY = 'solartwin-theme'
const LANG_KEY = 'solartwin-lang'
const themeMedia = window.matchMedia('(prefers-color-scheme: light)')
const themePicker = document.querySelector('.theme-picker')
const themeTrigger = document.querySelector('.theme-trigger')
const themeMenu = document.querySelector('.theme-menu')

const readStored = (key, fallback) => {
  try {
    return localStorage.getItem(key) || fallback
  } catch {
    return fallback
  }
}

const store = (key, value) => {
  try {
    localStorage.setItem(key, value)
  } catch {
    /* almacenamiento no disponible */
  }
}

let themeMode = readStored(THEME_KEY, 'auto')
if (!['auto', 'light', 'dark'].includes(themeMode)) themeMode = 'auto'

let lang = readStored(LANG_KEY, 'es') === 'en' ? 'en' : 'es'

const t = (key) => translations[lang]?.[key] ?? translations.es[key] ?? ''

/* ---------- Tema claro, oscuro y automático ---------- */

const resolveTheme = (mode) =>
  mode === 'auto' ? (themeMedia.matches ? 'light' : 'dark') : mode

const applyTheme = (mode, persist = true) => {
  themeMode = ['auto', 'light', 'dark'].includes(mode) ? mode : 'auto'
  const resolved = resolveTheme(themeMode)

  root.dataset.theme = resolved
  root.dataset.themeMode = themeMode

  document.querySelectorAll('[data-theme-set]').forEach((btn) => {
    const active = btn.dataset.themeSet === themeMode
    btn.setAttribute('aria-pressed', String(active))
    btn.setAttribute('aria-checked', String(active))
  })

  updateThemeLabel()

  const meta = document.querySelector('meta[name="theme-color"]')
  if (meta) meta.setAttribute('content', resolved === 'light' ? '#fdfaf6' : '#08070a')

  if (persist) store(THEME_KEY, themeMode)
}

applyTheme(themeMode, false)

document.querySelectorAll('[data-theme-set]').forEach((btn) => {
  btn.addEventListener('click', () => {
    applyTheme(btn.dataset.themeSet)
    closeThemeMenu()
    themeTrigger?.focus()
  })
})

themeMedia.addEventListener('change', () => {
  if (themeMode === 'auto') applyTheme('auto', false)
})

if (themePicker && themeTrigger && themeMenu) {
  themeTrigger.addEventListener('click', (event) => {
    event.stopPropagation()
    const open = themeMenu.hidden
    themeMenu.hidden = !open
    themeTrigger.setAttribute('aria-expanded', String(open))
  })

  document.addEventListener('click', (event) => {
    if (!themePicker.contains(event.target)) closeThemeMenu()
  })

  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') closeThemeMenu()
  })
}

/* ---------- Español e inglés ---------- */

const applyLanguage = (next, persist = true) => {
  lang = translations[next] ? next : 'es'
  const dict = translations[lang]

  root.lang = lang

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const value = dict[el.dataset.i18n]
    if (value === undefined) return
    if (el.hasAttribute('data-i18n-html')) el.innerHTML = value
    else el.textContent = value
  })

  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const value = dict[el.dataset.i18nAria]
    if (value !== undefined) el.setAttribute('aria-label', value)
  })

  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const value = dict[el.dataset.i18nTitle]
    if (value !== undefined) el.setAttribute('title', value)
  })

  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    const value = dict[el.dataset.i18nAlt]
    if (value !== undefined) el.setAttribute('alt', value)
  })

  const description = document.querySelector('meta[name="description"]')
  if (description) description.setAttribute('content', dict['meta.description'])
  document.title = dict['meta.title']

  document.querySelectorAll('[data-lang-set]').forEach((btn) => {
    btn.setAttribute('aria-pressed', String(btn.dataset.langSet === lang))
  })

  updateMenuLabel()
  updateThemeLabel()
  if (persist) store(LANG_KEY, lang)
}

document.querySelectorAll('[data-lang-set]').forEach((btn) => {
  btn.addEventListener('click', () => applyLanguage(btn.dataset.langSet))
})

/* ---------- Header y menú ---------- */

const header = document.querySelector('.site-header')
const nav = document.querySelector('#nav')
const navToggle = document.querySelector('.nav-toggle')
let navOpen = false

function updateMenuLabel() {
  if (!navToggle) return
  navToggle.setAttribute('aria-label', t(navOpen ? 'a11y.menuClose' : 'a11y.menuOpen'))
}

function updateThemeLabel() {
  if (!themeTrigger) return
  themeTrigger.setAttribute('aria-label', `${t('a11y.theme')}: ${t(`theme.${themeMode}`)}`)
}

function closeThemeMenu() {
  if (!themeMenu || !themeTrigger) return
  themeMenu.hidden = true
  themeTrigger.setAttribute('aria-expanded', 'false')
}

const onScroll = () => {
  header?.classList.toggle('is-scrolled', window.scrollY > 8)
}
onScroll()
window.addEventListener('scroll', onScroll, { passive: true })

if (navToggle && nav) {
  const closeNav = () => {
    navOpen = false
    nav.classList.remove('is-open')
    navToggle.setAttribute('aria-expanded', 'false')
    updateMenuLabel()
  }

  navToggle.addEventListener('click', () => {
    navOpen = nav.classList.toggle('is-open')
    navToggle.setAttribute('aria-expanded', String(navOpen))
    updateMenuLabel()
  })

  nav.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', closeNav)
  })

  window.addEventListener('resize', () => {
    if (window.innerWidth > 960) closeNav()
  })
}

applyLanguage(lang, false)

/* ---------- Aparición suave de los bloques ---------- */

const revealItems = document.querySelectorAll('[data-reveal]')
const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches

if (reduceMotion || !('IntersectionObserver' in window)) {
  revealItems.forEach((item) => item.classList.add('is-visible'))
} else {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible')
          observer.unobserve(entry.target)
        }
      })
    },
    { rootMargin: '0px 0px -8% 0px', threshold: 0.12 }
  )

  revealItems.forEach((item) => observer.observe(item))
}

/* ---------- Año actual en el pie de página ---------- */

const year = document.querySelector('#year')
if (year) year.textContent = String(new Date().getFullYear())
